function describe(gender, brand, name, own) {
  if (own) return own
  if (gender === 'copy') {
    const orig = brand.replace(/^Копия( · )?/, '')
    if (!orig) return known[keyOf('', name)] || 'Доступная версия популярного аромата с узнаваемым характером.'
    const base = known[keyOf(orig, name)]
    return `Близкая по звучанию версия аромата ${keyOf(orig, name)}.${base ? ' ' + base : ''}`
  }
  return known[keyOf(brand, name)] || GENERIC[gender](brand ? ' ' + brand : '')
}

